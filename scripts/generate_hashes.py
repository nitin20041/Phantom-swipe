#!/usr/bin/env python3
"""
generate_hashes.py
Computes SHA-256 hashes for all acquired evidence files, as required for
chain-of-custody integrity verification (Assignment Sub-Problem 2).

Usage:
    python3 scripts/generate_hashes.py
Writes results to hashes/hash_values.txt
"""

import hashlib
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET_DIRS = [ROOT / "evidence" / "skimmer_device", ROOT / "evidence" / "phone_device"]
OUTPUT_FILE = ROOT / "hashes" / "hash_values.txt"


def sha256_of_file(path: Path, chunk_size: int = 65536) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(chunk_size):
            h.update(chunk)
    return h.hexdigest()


def main():
    lines = ["# SHA-256 Hash Values — Operation Phantom Swipe Evidence", "# Generated by scripts/generate_hashes.py", ""]
    count = 0
    for d in TARGET_DIRS:
        if not d.exists():
            continue
        for path in sorted(d.iterdir()):
            if path.is_file():
                digest = sha256_of_file(path)
                rel = path.relative_to(ROOT)
                lines.append(f"{digest}  {rel}")
                count += 1
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text("\n".join(lines) + "\n")
    print(f"Hashed {count} files. Output written to {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
